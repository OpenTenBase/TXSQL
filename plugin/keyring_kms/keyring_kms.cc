/** keyring kms key generate interface. */
bool  kms_key_generate(const char *key_id, const char *key_type,
                       const char *user_id, size_t key_len)
{
  if (!is_kms_config_set) {
    kms_error = "config is not set.";
    return true;
  }

  /* 1.search and create cm_key_id if needed */
  std::string cm_key_id;
  if (kms_search_and_create_cm_key(cm_key_id)) {
    return true;
  }

  /* 2.generate data key */
  kms_action = "generate_data_key";
  std::string kms_encrypted_key;
  if (kms_generate_data_key(cm_key_id, key_len, kms_encrypted_key)) {
    return true;
  }

  /* 3.store encrypted key in key file */
  return mysql_key_store<keyring_kms::Key>(key_id, key_type, user_id,
                                           kms_encrypted_key.c_str(),
                                           kms_encrypted_key.length(),
                                           "keyring_kms");
}

