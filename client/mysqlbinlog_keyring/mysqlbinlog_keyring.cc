int kms_list_key_detail(std::string &cm_key_id){
  assert(kms_config.cfg_mode != KMS_CONFIG_UNINITIALIZED);
  Credential cred = Credential("","","");

  if (kms_structure_cred(cred)) {
    return 1;
  }

  KmsClient kms_client = KmsClient(cred, kms_config.region);
  kms_client.SetEndPoint(kms_config.end_point);

  if (keyring_kms_scheme == kms_scheme_type::KMS_SCHEME_HTTP) {
    set_kmsclient_profile(kms_client);
  }

  ListKeyDetailRequest list_key_req = ListKeyDetailRequest();
  list_key_req.SetOffset(0);
  list_key_req.SetLimit(10);

  if (kms_config.cfg_mode == KMS_CONFIG_USER_DEFINED) {
    /** set role to 0 to list key created by user itself */
    list_key_req.SetRole(0);

    /** if current kms config is user defined key, we user cm key id
    to listkeydetail*/
    list_key_req.SetSearchKeyAlias(kms_config.user_key_id);
  } else if (kms_config.cfg_mode == KMS_CONFIG_NON_USER_DEFINED) {
    /** set role to 1 to list key created by privilege granted  user*/
    list_key_req.SetRole(1);
    list_key_req.SetSearchKeyAlias(default_kms_key_alias);
  } else {
    kms_error = "ListKeyDetail fail because kms config is not set";
    error("%s.", kms_error.c_str());
    return 1;
  }

  auto list_key_res = kms_client.ListKeyDetail(list_key_req);
  if (!list_key_res.IsSuccess()) {
    kms_error = "ListKeyDetail fail:" + list_key_res.GetError().PrintAll();
    error("%s.", kms_error.c_str());
    return 1;
  }

  ListKeyDetailResponse list_key_rsp = list_key_res.GetResult();
  std::vector<KeyMetadata> metas;
  KeyMetadata key_meta;

  metas = list_key_rsp.GetKeyMetadatas();

  cm_key_id = "";
  for (unsigned int i = 0; i < metas.size(); i++) {
    key_meta = metas[i];
    if ((kms_config.cfg_mode == KMS_CONFIG_NON_USER_DEFINED
         && key_meta.GetAlias() == default_kms_key_alias)
         || (kms_config.cfg_mode == KMS_CONFIG_USER_DEFINED
         && key_meta.GetKeyId() == kms_config.user_key_id)) {
      cm_key_id = key_meta.GetKeyId();
      break;
    }
  }

  return 0;
}

int kms_config_check() {
  std::string   cm_key_id;
  if (kms_list_key_detail(cm_key_id)) {
    return 1;
  }

  /* If we use user defined cm key, we should guarantee that cm key exists.*/
  if (kms_config.cfg_mode == KMS_CONFIG_USER_DEFINED) {
    if (cm_key_id.length() != 0) {
      return 0;
    } else {
      kms_error = "Can't find cmkey , id: " + kms_config.user_key_id;
      error("%s.", kms_error.c_str());
      return 1;
    }
  }

  return 0;
}

int parse_and_set_role(string& role_type){
  int type = find_type(role_type.c_str(), &keyring_kms_role_typelib,
                       FIND_TYPE_NO_PREFIX);
  /* Set "none" is invalid */
  if (type <= 1) {
    return 1;
  }
  keyring_kms_roletype = static_cast<ulong>(type - 1);

  return 0;
}

