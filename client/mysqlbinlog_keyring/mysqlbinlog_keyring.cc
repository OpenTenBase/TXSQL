int kms_get_session_token(string& session_token,
                          string& secret_id,
                          string& secret_key) {

  Credential cred = Credential(kms_config.secret_id, kms_config.secret_key);

  AssumeRoleRequest assume_req = AssumeRoleRequest();
  string roleArn = "qcs::cam::uin/";
  roleArn.append(kms_config.uin);

  switch (keyring_kms_roletype) {
  case kms_role_type::KMS_ROLE_SERVICELINKEDROLE:
      roleArn.append(":role/tencentcloudServiceRoleName/");
      break;
  case kms_role_type::KMS_ROLE_SERVICEROLE:
      roleArn.append(":roleName/");
      break;
  default:
      roleArn.append(":roleName/");
      break;
  }

  roleArn.append(kms_config.role_name);
  assume_req.SetRoleArn(roleArn);
  assume_req.SetRoleSessionName(kms_session_name);
  assume_req.SetDurationSeconds(kms_duration_seconds);
  StsClient sts_client = StsClient(cred, kms_config.region);
  sts_client.SetEndPoint(kms_config.cam_point);

  if (keyring_kms_scheme == kms_scheme_type::KMS_SCHEME_HTTP) {
    set_stsclient_profile(sts_client);
  }

  auto outcome = sts_client.AssumeRole(assume_req);
  if (!outcome.IsSuccess()) {
    kms_error = "AssumeRole fail:" + outcome.GetError().PrintAll();
    error("%s.", kms_error.c_str());
    return 1;
  }

  AssumeRoleResponse assume_rsp = outcome.GetResult();
  Credentials tmp_cred = assume_rsp.GetCredentials();

  session_token = tmp_cred.GetToken();
  secret_id = tmp_cred.GetTmpSecretId();
  secret_key = tmp_cred.GetTmpSecretKey();
  return 0;
}

/** Set the credential  of kmsclient */
int kms_structure_cred(Credential& cred){
  if (keyring_kms_isprivate) {
    cred.SetSecretId(kms_config.secret_id);
    cred.SetSecretKey(kms_config.secret_key);
  } else {
    /* Get session token from cam. */
    string session_token;
    string secret_id;
    string secret_key;
    if (kms_get_session_token(session_token, secret_id, secret_key)) {
      return 1;
    }
    cred.SetSecretId(secret_id);
    cred.SetSecretKey(secret_key);
    cred.SetToken(session_token);
  }

  return 0;
}

