bool load_field_size(const uchar *buffer, size_t *buffer_position,
                          size_t key_pod_size, size_t *field_length) {
  if (key_pod_size < *buffer_position + sizeof(size_t)) return true;
  *field_length = *reinterpret_cast<const size_t *>(buffer + *buffer_position);
  *buffer_position += sizeof(size_t);

  return false;
}

bool load_string_from_buffer(const uchar *buffer, size_t *buffer_position,
                                  size_t key_pod_size, string *string,
                                  size_t string_length) {
  if (key_pod_size < *buffer_position + string_length) return true;

  string->assign(reinterpret_cast<const char *>(buffer) + *buffer_position,
                 string_length);
  *buffer_position += string_length;

  return false;
}

bool load_from_buffer(uchar *buffer,
                      size_t *number_of_bytes_read_from_buffer,
                      size_t input_buffer_size) {
  size_t key_pod_size;
  size_t key_id_length;
  size_t key_type_length;
  size_t user_id_length;
  size_t buffer_position = 0;

  if (input_buffer_size < buffer_position + sizeof(size_t)) return true;

  key_pod_size = *reinterpret_cast<size_t *>(buffer + buffer_position);

  if (input_buffer_size < buffer_position + key_pod_size) return true;

  buffer_position += sizeof(size_t);
  mysqlbinlog_key cur_key;
  if (load_field_size(buffer, &buffer_position, key_pod_size, &key_id_length) ||
      load_field_size(buffer, &buffer_position, key_pod_size,
                      &key_type_length) ||
      load_field_size(buffer, &buffer_position, key_pod_size,
                      &user_id_length) ||
      load_field_size(buffer, &buffer_position, key_pod_size, &cur_key.key_len))
    return true;
  if (load_string_from_buffer(buffer, &buffer_position, key_pod_size, &cur_key.key_id,
                              key_id_length) ||
      load_string_from_buffer(buffer, &buffer_position, key_pod_size, &cur_key.key_type,
                              key_type_length) ||
      load_string_from_buffer(buffer, &buffer_position, key_pod_size, &cur_key.user_id,
                              user_id_length))
    return true;
  cur_key.key.reset(new uchar[cur_key.key_len]);
  memcpy(cur_key.key.get(), buffer + buffer_position, cur_key.key_len);
  buffer_position += cur_key.key_len;

  size_t padding =
      (sizeof(size_t) - (buffer_position % sizeof(size_t))) % sizeof(size_t);
  buffer_position += padding;

  *number_of_bytes_read_from_buffer = buffer_position;
  g_hash_mysqlbinlog_key[cur_key.key_id] = cur_key;

  return false;
}

bool load_file_into_buffer(FILE *file){
  /* keyring_kms has the same logic as keyring in load_file_into_buffer(), there use keyring_kms source code*/

  /* 1.only read the data of key into buffer*/
  fseek(file, 0L, SEEK_END);
	size_t file_size = ftell(file);
	size_t input_buffer_size = file_size - keyring_kms::Checker::EOF_TAG_SIZE - keyring_file_version_2_0.length() - SHA256_DIGEST_LENGTH;
	fseek(file , keyring_file_version_2_0.length(), SEEK_SET);
  unique_ptr<uchar[]> tmp = make_unique<uchar[]>(input_buffer_size);
	auto res [[maybe_unused]] = fread(tmp.get(), input_buffer_size, 1, file);

  /* 2.checks whether keyring file matches any known keyring file structure */
  keyring_kms::CheckerFactory checker_factory;
  auto checker = checker_factory.getCheckerForVersion(keyring_file_version_2_0);
  keyring_kms::Converter::Arch file_arch(keyring_kms::Converter::Arch::UNKNOWN);
  keyring_kms::Converter::Arch native_arch(keyring_kms::Converter::get_native_arch());
  keyring_kms::Digest digest(keyring_kms::DigestKind::SHA256, keyring_kms::dummy_digest);
  if(checker->check_file_structure(fileno(file), file_size, &digest, &file_arch)) {
    return true;
  };

  /* 3.if machine architecture of the input key data is not same as current machine architecture, convert it */
  std::string converted;
  if(file_arch != native_arch){
    keyring_kms::Converter::convert_data(reinterpret_cast<const char *>(tmp.get()),
                                  input_buffer_size, file_arch, native_arch,
                                  converted);
    tmp.release();
    tmp = make_unique<uchar[]>(converted.length());
    memcpy(tmp.get(), converted.c_str(), converted.length());
  }

  /* 4. Parse the mysqlbinlog_key structure from the buffer */
	size_t position = 0;
  size_t number_of_bytes_read_from_buffer = 0;
	while(position < input_buffer_size &&
        load_from_buffer(tmp.get() + position, &number_of_bytes_read_from_buffer, input_buffer_size - position) == false) {
    position += number_of_bytes_read_from_buffer;
  };
  return false;
}

void xor_data() {
  static const char *obfuscate_str = "*305=Ljt0*!@$Hnm(*-9-w;:";
  for (auto &val : g_hash_mysqlbinlog_key) {
    for (size_t i = 0, l = 0; i < val.second.key_len;
      ++i, l = ((l + 1) % strlen(obfuscate_str)))
      val.second.key.get()[i] ^= obfuscate_str[l];

    if (val.second.key_id == mysqlbinlog_kms::kms_config_key_id)
      is_kms = true;
  }
}

/*  Decrypted entry function, used to initialize the keyring hash map */
bool init_mysqlbinlog_key(std::string file_name){
	FILE* keyring_file = nullptr;
	keyring_file = fopen(file_name.c_str(), "r");
  if (keyring_file == nullptr) {
    error("Could not open keyring file %s.", file_name.c_str());
    return true;
  }
  /* 1.read keyring in buffer */
	if (load_file_into_buffer(keyring_file)) {
    fclose(keyring_file);
    error("%s is malformed.", file_name.c_str());
    return true;
  }
	fclose(keyring_file);
  /* 2.XOR conversion */
	xor_data();
  /* 3.if keyring_file has "kms_config_data", decrypt key data */
  if (is_kms && mysqlbinlog_kms::set_kms_config_and_decrypt_master_key()) {
    return true;
  }
  return false;
}
